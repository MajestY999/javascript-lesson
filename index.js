// Основные идеи
// Массив задач хранится как константа tasks, где каждый элемент — строка.
// Для добавления элемента в конец массива используется метод push.
// Для поиска индекса элемента по значению используется метод indexOf, который возвращает -1, если элемент не найден.
// Для удаления элемента по индексу используется метод splice.
// Для добавления элемента в начало массива используется метод unshift.
// Приоритизация — это сочетание удаления элемента с его старого места и вставки в начало массива.
// Все три функции модифицируют исходный массив напрямую (не являются чистыми функциями).
// Если переданное название задачи не найдено в массиве (indexOf возвращает -1), функция должна завершаться досрочно через return, чтобы не повредить данные.

const tasks = ["Задача 1"];

function addTask(task) {
  return tasks.push(task); //используя метод push мы создаем задачу в которой создается элемент в конец массива
}

function deleteTask(task) {
  const index = tasks.indexOf(task); //проверяет по индексу, индекс нашего элемента который записан в массив
  if (index >= 0) {
    tasks.splice(index, 1); // при наличии нашего элемента в массиве удаляется один элемент из массива который мы написали для удаления
  }
}

function prioritate(task) {
  const index = tasks.indexOf(task);
  if (index === -1) {
    return;
  }
  tasks.splice(index, 1);
  tasks.unshift(task);
}

